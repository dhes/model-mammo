function App() {
  const [patients, setPatients] = useState([])
  const [selectedPatientId, setSelectedPatientId] = useState('')
  const [selectedPatient, setSelectedPatient] = useState(null)
  const [cdsResults, setCdsResults] = useState([]) // Array of { guideline, result }
  const [loading, setLoading] = useState(false)
  const [error, setError] = useState(null)
  const [executionTime, setExecutionTime] = useState(null)
  const [fhirReady, setFhirReady] = useState(false)
  const [launchMode, setLaunchMode] = useState(null) // 'standalone' or 'smart'
  const [cqlMode, setCqlMode] = useState(DEFAULT_CQL_MODE) // 'client' or 'server'

  // Check if ELM is loaded
  const elmLoaded = Object.keys(elmLibraries).length > 0

  // Initialize FHIR client on mount
  useEffect(() => {
    initFhirClient()
  }, [])

  // Fetch patients after FHIR client is ready (standalone mode only)
  useEffect(() => {
    if (fhirReady && launchMode === 'standalone') {
      fetchPatients()
    }
  }, [fhirReady, launchMode])

  // Evaluate CDS when patient is selected or CQL mode changes
  useEffect(() => {
    if (selectedPatientId) {
      evaluateCds(selectedPatientId)
    } else {
      setCdsResults([])
      setSelectedPatient(null)
      setExecutionTime(null)
    }
  }, [selectedPatientId, cqlMode])

  async function initFhirClient() {
    try {
      await fhirService.initAuto('/fhir')
      setFhirReady(true)
      setLaunchMode(fhirService.mode)

      // If SMART launch, try to get patient from context
      if (fhirService.mode === 'smart') {
        const contextPatient = await fhirService.getPatientFromContext()
        if (contextPatient) {
          setSelectedPatientId(contextPatient.id)
          setSelectedPatient(contextPatient)
        }
      }

      console.log(`[App] FHIR initialized: ${fhirService.mode} mode, server: ${fhirService.getServerUrl()}`)
    } catch (err) {
      setError('Failed to initialize FHIR client: ' + err.message)
    }
  }

  async function fetchPatients() {
    try {
      const tagBase = 'http://example.org/test-lifecycle'
      const guidelineTags = Object.keys(GUIDELINE_CONFIG).map(prefix => `${prefix}-test`)

      const patientList = await fhirService.fetchPatientsByTag(tagBase, guidelineTags)
      patientList.sort((a, b) => a.id.localeCompare(b.id))
      setPatients(patientList)
    } catch (err) {
      setError('Failed to fetch patients: ' + err.message)
    }
  }

  function getApplicableGuidelines(patient, bundle) {
    const applicable = []
    const age = getPatientAge(patient)
    const gender = patient.gender?.toLowerCase()

    // First, check for test tags (used with HAPI test patients)
    // If tagged, only return the tagged guideline
    const tags = patient.meta?.tag || []
    for (const tag of tags) {
      if (tag.system === 'http://example.org/test-lifecycle') {
        const prefix = tag.code?.split('-')[0]
        if (prefix && GUIDELINE_CONFIG[prefix]) {
          return [GUIDELINE_CONFIG[prefix]]
        }
      }
    }

    // For real patients: check eligibility for ALL guidelines

    // Breast Cancer Screening: female, age 40-74
    if (gender === 'female' && age >= 40 && age <= 74) {
      applicable.push(GUIDELINE_CONFIG.bcs)
    }

    // Cervical Cancer Screening: female, age 21-65
    if (gender === 'female' && age >= 21 && age <= 65) {
      applicable.push(GUIDELINE_CONFIG.ccs)
    }

    // Tobacco Screening: adults 18+
    if (age >= 18) {
      applicable.push(GUIDELINE_CONFIG.tob)
    }

    // Colorectal Cancer Screening: age 46-75
    if (age >= 46 && age <= 75) {
      applicable.push(GUIDELINE_CONFIG.crc)
    }

    // Folic Acid Supplementation: female, age 15-45
    if (gender === 'female' && age >= 15 && age <= 45) {
      applicable.push(GUIDELINE_CONFIG.fol)
    }

    // Ophthalmia Neonatorum Prophylaxis: newborns (age <= 28 days)
    // Age in days: if birthDate is within last 28 days
    if (age === 0) {
      applicable.push(GUIDELINE_CONFIG.onp)
    }

    // Hypertension Screening: adults 18+
    if (age >= 18) {
      applicable.push(GUIDELINE_CONFIG.htn)
    }

    // HIV Screening (Age-Based): ages 15-65 universal, or any age with risk factors
    if (age >= 15 && age <= 65) {
      applicable.push(GUIDELINE_CONFIG.hiv)
    }

    // HIV PrEP: age >= 13 (adolescents and adults)
    if (age >= 13) {
      applicable.push(GUIDELINE_CONFIG.prp)
    }

    // Syphilis Screening: adolescents/adults (age >= 12) with risk factors
    // For real patients, always include - CQL will determine if at-risk
    if (age >= 12) {
      applicable.push(GUIDELINE_CONFIG.syp)
    }

    // Pregnancy-specific guidelines: check bundle for active pregnancy Condition
    const isPregnant = bundle?.entry?.some(e => {
      const r = e.resource
      return r?.resourceType === 'Condition'
        && r?.code?.coding?.some(c => c.system === 'http://snomed.info/sct' && c.code === '77386006')
        && (r?.clinicalStatus?.coding?.[0]?.code === 'active' || !r?.clinicalStatus)
    })

    if (isPregnant) {
      applicable.push(GUIDELINE_CONFIG.hbv)
      applicable.push(GUIDELINE_CONFIG.rhd)
      applicable.push(GUIDELINE_CONFIG.hvp)
    }

    return applicable
  }

  async function evaluateCds(patientId) {
    setLoading(true)
    setError(null)
    setCdsResults([])
    setExecutionTime(null)

    try {
      // Fetch patient and build bundle using fhirService
      const bundle = await fhirService.buildPatientBundle(patientId)
      const patient = bundle.entry.find(e => e.resource?.resourceType === 'Patient')?.resource
      setSelectedPatient(patient)

      // Determine which guidelines apply to this patient
      const guidelines = getApplicableGuidelines(patient, bundle)
      if (guidelines.length === 0) {
        setError('No applicable CDS guidelines found for this patient')
        return
      }

      // Check if ELM is loaded (only needed for client-side mode)
      if (cqlMode === 'client' && !elmLoaded) {
        setError('ELM libraries not loaded. Complete the setup steps first.')
        return
      }

      // Execute CQL for ALL applicable guidelines in parallel
      const startTime = performance.now()
      const results = await Promise.all(
        guidelines.map(async (guideline) => {
          let result
          if (cqlMode === 'server') {
            // Server-side execution via HAPI $evaluate
            result = await fhirService.evaluateCqlOnServer(
              DEFAULT_CQL_SERVER_URL,
              guideline.libraryId,
              bundle
            )
          } else {
            // Client-side execution via cql-execution (JavaScript)
            const rawResult = await executeCqlLocally(guideline.libraryId, bundle)
            result = normalizeResults(rawResult)
          }
          return { guideline, result }
        })
      )
      const endTime = performance.now()
      setExecutionTime(Math.round(endTime - startTime))

      setCdsResults(results)
    } catch (err) {
      setError('Failed to evaluate CDS: ' + err.message)
    } finally {
      setLoading(false)
    }
  }

  function getPatientDisplayName(patient) {
    if (!patient) return ''
    const name = patient.name?.[0]
    if (name) {
      const given = name.given?.join(' ') || ''
      const family = name.family || ''
      return `${given} ${family}`.trim() || patient.id
    }
    return patient.id
  }

  function getPatientAge(patient) {
    if (!patient?.birthDate) return null
    const [year, month, day] = patient.birthDate.split('-').map(Number)
    const birth = new Date(year, month - 1, day)
    const today = new Date()
    let age = today.getFullYear() - birth.getFullYear()
    const monthDiff = today.getMonth() - birth.getMonth()
    if (monthDiff < 0 || (monthDiff === 0 && today.getDate() < birth.getDate())) {
      age--
    }
    return age
  }

  // Helper to render a single CDS card
  function renderCdsCard({ guideline, result }) {
    const alerts = guideline.getAlerts(result)
    const activeAlerts = alerts.filter(a => a.active || a.inactiveText)
    const hasPositiveRecommendation = alerts.some(a => a.active)

    return (
      <section
        key={guideline.libraryId}
        className={`cds-card ${hasPositiveRecommendation ? 'recommend' : 'no-recommend'}`}
      >
        <h2>CDS Recommendation: {guideline.title}</h2>

        {activeAlerts.length === 0 && (
          <div className="recommendation">
            <span className="icon">-</span>
            <span className="text">No Action Required</span>
          </div>
        )}

        {activeAlerts.map(alert => (
          <div key={alert.key} className="recommendation">
            {alert.active ? (
              <>
                <span className="icon">+</span>
                <span className="text">{alert.activeText}</span>
              </>
            ) : (
              <>
                <span className="icon">-</span>
                <span className="text">{alert.inactiveText}</span>
              </>
            )}
          </div>
        ))}

        <details className="cds-details">
          <summary>View Decision Factors</summary>
          <dl>
            {guideline.getDetails(result).map(({ label, value }) => (
              <React.Fragment key={label}>
                <dt>{label}</dt>
                <dd>{String(value ?? 'N/A')}</dd>
              </React.Fragment>
            ))}
          </dl>
        </details>
      </section>
    )
  }

  return (
    <div className="app">
      <header className="header">
        <h1>
          USPSTF Clinical Decision Support
          <span className="mode-badge">
            {launchMode === 'smart' ? 'SMART Launch' : 'Standalone'}
          </span>
        </h1>
        <p className="subtitle">
          {fhirReady
            ? `Connected to: ${fhirService.getServerUrl()}`
            : 'Initializing FHIR client...'}
        </p>
        <div className="cql-mode-toggle">
          <label>
            CQL Engine:
            <select
              value={cqlMode}
              onChange={(e) => setCqlMode(e.target.value)}
            >
              <option value="client">Client (JavaScript)</option>
              <option value="server">Server (HAPI Java)</option>
            </select>
          </label>
          <span className="cql-mode-info">
            {cqlMode === 'server'
              ? 'Using HAPI $evaluate (100% accurate)'
              : 'Using cql-execution (browser)'}
          </span>
        </div>
      </header>

      <main className="main">
        {!elmLoaded && (
          <div className="error-card">
            <strong>Setup Required:</strong> ELM libraries not loaded.
            <br /><br />
            Run these commands:
            <pre style={{ marginTop: '0.5rem', fontSize: '0.8rem' }}>
{`# 1. Compile CQL to ELM
cd tools/cql-translator
sdk use java 21.0.6-tem
mvn exec:java -q -Dexec.args="..."

# 2. Copy ELM to smart-app/src/elm/

# 3. Uncomment imports in App.jsx`}
            </pre>
          </div>
        )}

        {/* Patient selector - shown in standalone mode or if SMART launch has no patient */}
        {launchMode === 'standalone' && (
          <section className="patient-selector">
            <label htmlFor="patient-select">Select Patient:</label>
            <select
              id="patient-select"
              value={selectedPatientId}
              onChange={(e) => setSelectedPatientId(e.target.value)}
              disabled={!fhirReady}
            >
              <option value="">-- Select a patient --</option>
              {patients.map(patient => (
                <option key={patient.id} value={patient.id}>
                  {patient.id}
                </option>
              ))}
            </select>
          </section>
        )}

        {launchMode === 'smart' && selectedPatient && (
          <div className="smart-context-info">
            Patient from EHR context: <strong>{selectedPatient.id}</strong>
          </div>
        )}

        {error && (
          <div className="error-card">
            {error}
          </div>
        )}

        {loading && (
          <div className="loading">
            Evaluating CDS {cqlMode === 'server' ? 'via HAPI server' : 'locally'}...
          </div>
        )}

        {executionTime !== null && !loading && (
          <div className="execution-info">
            CQL executed in <code>{executionTime}ms</code>
            {cqlMode === 'server'
              ? ' (server-side via HAPI $evaluate)'
              : ' (client-side, no server round-trip)'}
          </div>
        )}

        {selectedPatient && !loading && (
          <section className="patient-info">
            <h2>Patient Information</h2>
            <dl>
              <dt>ID</dt>
              <dd>{selectedPatient.id}</dd>
              <dt>Name</dt>
              <dd>{getPatientDisplayName(selectedPatient)}</dd>
              <dt>Gender</dt>
              <dd>{selectedPatient.gender || 'Unknown'}</dd>
              <dt>Birth Date</dt>
              <dd>{selectedPatient.birthDate || 'Unknown'}</dd>
              <dt>Age</dt>
              <dd>{getPatientAge(selectedPatient) ?? 'Unknown'} years</dd>
            </dl>
          </section>
        )}

        {cdsResults.length > 0 && !loading && (
          <div className="cds-cards">
            {cdsResults.map(renderCdsCard)}
          </div>
        )}
      </main>

      <footer className="footer">
        <p>SMART on FHIR + Local CQL Execution Demo</p>
      </footer>
    </div>
  )
}

export default App
