// CQL Execution Engine (Client-Side)
// =============================================================================
async function executeCqlLocally(libraryId, patientBundle) {
  const elmJson = elmLibraries[libraryId]
  if (!elmJson) {
    throw new Error(`ELM not loaded for library: ${libraryId}. Run the setup steps first.`)
  }

  // Build repository with all dependent libraries
  const repository = new Repository(Object.values(elmLibraries))

  // Create the main library
  const library = new Library(elmJson, repository)

  // Create executor with code service for ValueSet lookups
  const executor = new Executor(library, codeService)

  // Create FHIR R4 patient source
  const patientSource = PatientSource.FHIRv401()

  // Debug: log bundle structure
  console.log('Patient bundle:', JSON.stringify(patientBundle, null, 2).slice(0, 500))

  patientSource.loadBundles([patientBundle])

  // Execute CQL (exec returns a Promise)
  const results = await executor.exec(patientSource)

  // Debug: log full results structure
  console.log('CQL execution results:', results)
  console.log('patientResults:', results?.patientResults)
  console.log('unfilteredResults:', results?.unfilteredResults)

  // Extract patient ID
  const patientId = patientBundle.entry
    ?.find(e => e.resource?.resourceType === 'Patient')
    ?.resource?.id
  console.log('Looking for patientId:', patientId)

  // Try different result access patterns
  if (results?.patientResults) {
    console.log('patientResults keys:', Object.keys(results.patientResults))
    return results.patientResults[patientId] || {}
  }

  // Fallback: maybe results is the patient results directly
  if (results && typeof results === 'object' && !results.patientResults) {
    console.log('Using results directly')
    return results
  }

  return {}
}

